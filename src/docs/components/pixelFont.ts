export interface PixelCell {
    x: number
    y: number
}

/**
 * Every lit cell in a word, in reading order, on a grid one column of gap wide
 * between letters.
 */
export function pixelCells(text: string): { cells: PixelCell[]; width: number } {
    const letters = [...text.toUpperCase()]
    const cells: PixelCell[] = []
    let cursor = 0

    for (const letter of letters) {
        const glyph = GLYPHS[letter] ?? GLYPHS[" "]
        const rows = glyph.split(",")

        rows.forEach((row, y) => {
            for (let x = 0; x < row.length; x += 1) {
                if (row[x] === "1") cells.push({ x: cursor + x, y })
            }
        })

        cursor += PIXEL_GLYPH_WIDTH + 1
    }

    return { cells, width: Math.max(0, cursor - 1) }
}
