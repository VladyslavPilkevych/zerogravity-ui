export const GLYPH_COLS = 5
export const GLYPH_ROWS = 7
/** blank columns between two glyphs */
export const GLYPH_GAP = 1

export interface GridCell {
    col: number
    row: number
}

export interface TextGrid {
    cols: number
    rows: number
    cells: readonly GridCell[]
}

export function supports(character: string): boolean {
    return character.toUpperCase() in GLYPHS
}

export const SUPPORTED_CHARACTERS = Object.keys(GLYPHS).join("")

/**
 * Turns a string into a grid of filled cells. Unsupported characters fall back to
 * a blank slot so the layout never collapses.
 */
export function textGrid(text: string): TextGrid {
    const letters = Array.from(text.toUpperCase())
    if (letters.length === 0) return { cols: 0, rows: GLYPH_ROWS, cells: [] }

    const cells: GridCell[] = []
    let offset = 0

    for (const letter of letters) {
        const glyph = GLYPHS[letter] ?? GLYPHS[" "]

        glyph.forEach((line, row) => {
            Array.from(line).forEach((mark, col) => {
                if (mark === "1") cells.push({ col: offset + col, row })
            })
        })

        offset += GLYPH_COLS + GLYPH_GAP
    }

    return {
        cols: Math.max(1, offset - GLYPH_GAP),
        rows: GLYPH_ROWS,
        cells,
    }
}
