const FALLBACK = "11111,10001,10001,10001,10001,10001,11111"

export const BITMAP_CHARACTERS = Object.keys(GLYPHS).join("")

export interface BitmapCell {
    x: number
    y: number
}

export interface BitmapLayout {
    cells: BitmapCell[]
    width: number
    height: number
}

function glyphFor(character: string): string {
    const upper = character.toUpperCase()
    if (upper in GLYPHS) return GLYPHS[upper]
    if (/\s/.test(character)) return GLYPHS[" "]
    const bare = upper.normalize("NFD").replace(/[̀-ͯ]/g, "")
    return GLYPHS[bare] ?? FALLBACK
}

export function layoutBitmap(text: string, tracking = 1): BitmapLayout {
    const space = Math.max(0, Math.round(tracking))
    const cells: BitmapCell[] = []
    let cursor = 0
    let first = true

    for (const character of Array.from(text)) {
        if (!first) cursor += space
        first = false

        const rows = glyphFor(character).split(",")
        rows.forEach((row, y) => {
            for (let x = 0; x < row.length; x += 1) {
                if (row[x] === "1") cells.push({ x: cursor + x, y })
            }
        })
        cursor += rows[0].length
    }

    return { cells, width: cursor, height: BITMAP_ROWS }
}
